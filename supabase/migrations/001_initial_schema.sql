create or replace function public.crm_submit_contact(
  p_email text, p_name text default null, p_phone text default null, p_sms_opt_in boolean default false,
  p_source text default null, p_metadata jsonb default '{}'::jsonb
) returns void language plpgsql security definer set search_path = public as $$
begin
  insert into public.crm_contacts(email,name,phone,sms_opt_in,source,metadata)
  values(lower(trim(p_email)),p_name,p_phone,p_sms_opt_in,p_source,coalesce(p_metadata,'{}'::jsonb))
  on conflict(email) do update set
    name=coalesce(excluded.name, crm_contacts.name), phone=coalesce(excluded.phone, crm_contacts.phone),
    sms_opt_in=excluded.sms_opt_in, source=coalesce(excluded.source, crm_contacts.source),
    metadata=crm_contacts.metadata || excluded.metadata, updated_at=now();
end $$;

grant execute on function public.crm_submit_contact(text,text,text,boolean,text,jsonb) to anon, authenticated;

