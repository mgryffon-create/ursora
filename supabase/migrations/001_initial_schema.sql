DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['tickers','quotes','market_snapshots','market_movers','analysis_runs','signals','contract_candidates','risk_assessments','news_items','filings','transcript_statements','sentiment_readings','economic_events','earnings_events','signal_updates','signal_feed_events','ohlcv_bars','provider_configs','lit_constructs','lit_studies','lit_construct_studies']
  LOOP
    EXECUTE format('alter table public.%I enable row level security', t);
    EXECUTE format('drop policy if exists %I on public.%I', 'public read', t);
    EXECUTE format('create policy %I on public.%I for select using (true)', 'public read', t);
  END LOOP;
END $$;

