create table if not exists public.historical_trade_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  brokerage_episode_id bigint not null references public.snaptrade_trade_episodes(id) on delete cascade,
  symbol text not null,
  entry_at timestamptz not null,
  exit_at timestamptz,
  retro_direction text not null default 'neutral',
  thesis_state text not null default 'unconfirmed',
  setup_class text not null default 'unconfirmed',
  cycle_event_type text not null default 'unconfirmed',
  reversal_origin numeric,
  confirmation_price numeric,
  confirmation_at timestamptz,
  entry_underlying_price numeric,
  exit_underlying_price numeric,
  target_price numeric,
  invalidation_price numeric,
  target_hit_at timestamptz,
  invalidation_at timestamptz,
  directional_agreement text not null default 'unconfirmed',
  entry_relationship text not null default 'unconfirmed',
  exit_relationship text not null default 'unconfirmed',
  range_position_5d numeric,
  range_position_20d numeric,
  volume_confirmation_ratio numeric,
  move_extension_at_entry numeric,
  mfe_underlying_pct numeric,
  mae_underlying_pct numeric,
  post_invalidation_minutes integer,
  confidence_score numeric,
  review_summary text,
  evidence jsonb not null default '{}'::jsonb,
  engine_version text not null default 'historical-cycle-1.0',
  computed_at timestamptz not null default now(),
  unique(user_id, brokerage_episode_id)
);

create index if not exists historical_trade_reviews_user_idx
  on public.historical_trade_reviews(user_id, computed_at desc);

create index if not exists historical_trade_reviews_symbol_idx
  on public.historical_trade_reviews(user_id, symbol, entry_at desc);

alter table public.historical_trade_reviews enable row level security;

drop policy if exists "own historical trade reviews" on public.historical_trade_reviews;
create policy "own historical trade reviews"
  on public.historical_trade_reviews
  for all
  using (user_id = auth.uid())
  with check (user_id = auth.uid());
